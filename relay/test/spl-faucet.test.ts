/** A classic SPL mint account's data (82 bytes). */
function mintData(authority: string | null, decimals: number): Uint8Array {
  const d = new Uint8Array(82);
  const v = new DataView(d.buffer);
  if (authority) {
    v.setUint32(0, 1, true);
    d.set(decodeKey(authority), 4);
  }
  d[44] = decimals;
  d[45] = 1;
  return d;
}

// ── a mock chain that runs the faucet's two instructions ─────────────────────────────────────────────

interface Decoded {
  signers: number;
  keys: string[];
  ixs: { program: string; accounts: string[]; data: Uint8Array }[];
}
function decodeMessage(m: Uint8Array): Decoded {
  let at = 0;
  const vec = () => {
    let n = 0;
    let shift = 0;
    for (;;) {
      const b = m[at++]!;
      n |= (b & 0x7f) << shift;
      if ((b & 0x80) === 0) return n;
      shift += 7;
    }
  };
  const signers = m[0]!;
  at = 3;
  const nk = vec();
  const keys = Array.from({ length: nk }, (_, i) => encodeKey(m.slice(at + 32 * i, at + 32 * (i + 1))));
  at += 32 * nk + 32;
  const ni = vec();
  const ixs: Decoded['ixs'] = [];
  for (let i = 0; i < ni; i++) {
    const program = keys[m[at++]!]!;
    const na = vec();
    const accounts = Array.from(m.slice(at, at + na)).map((x) => keys[x]!);
    at += na;
    const nd = vec();
    ixs.push({ program, accounts, data: m.slice(at, at + nd) });
    at += nd;
  }
  return { signers, keys, ixs };
}

interface Chain {
  rpc: MockSolanaRpc;
  /** The next sends: accepted by the RPC but never land (status null). */
  drop: boolean;
  /** The next sends are refused by the RPC with this message (preflight). */
  refuse: string | null;
  balance(owner: string, mint: string): bigint;
  fetch: FaucetFetch;
}

function mockChain(genesisHash?: string): Chain {
  const rpc = mockSolanaRpc(genesisHash ? { genesisHash } : {});
  const inner = rpc.handler;
  const c: Chain = {
    rpc,
    drop: false,
    refuse: null,
    balance: (owner, mint) => rpc.tokenBalances.get(associatedTokenAddress(owner, mint))?.amount ?? 0n,
    fetch: asFetch(async (req) => {
      const text = await req.text();
      const body = JSON.parse(text) as { id: unknown; method: string; params?: unknown[] };
      const again = () => inner(new Request(req.url, { method: 'POST', body: text }));
      if (body.method !== 'sendTransaction') return again();
      if (c.refuse) return json({ jsonrpc: '2.0', id: body.id, error: { code: -32002, message: c.refuse } });
      const res = await again();
      const out = (await res.clone().json()) as { result?: string };
      if (!out.result) return res;
      const wire = Uint8Array.from(Buffer.from(String(body.params![0]), 'base64'));
      const { problem, apply } = runFaucetTx(rpc, wire);
      if (problem || c.drop) rpc.sent.pop();
      else apply();
      if (problem)
        return json({
          jsonrpc: '2.0',
          id: body.id,
          error: { code: -32002, message: `Transaction simulation failed: ${problem}` },
        });
      return res;
    }),
  };
  return c;
}

/** Validate the ATA CreateIdempotent and MintToChecked instructions (nothing else allowed); `apply` lands them. */
function runFaucetTx(rpc: MockSolanaRpc, wire: Uint8Array): { problem: string | null; apply: () => void } {
  const problem = (p: string) => ({ problem: p, apply: () => {} });
  const d = decodeMessage(splitTransaction(wire).message);
  const signers = new Set(d.keys.slice(0, d.signers));
  const effects: (() => void)[] = [];
  const created = new Set<string>();
  for (const ix of d.ixs) {
    if (ix.program === ASSOCIATED_TOKEN_PROGRAM_ID && ix.data.length === 1 && ix.data[0] === 1) {
      const [payer, ata, owner, mint] = ix.accounts;
      if (!signers.has(payer!)) return problem('the payer did not sign');
      if (associatedTokenAddress(owner!, mint!) !== ata) return problem('not the associated token address');
      const m = rpc.accounts.get(mint!);
      if (!m) return problem('no such mint');
      if (!rpc.accounts.has(ata!) && !created.has(ata!)) {
        created.add(ata!);
        const decimals = parseMintAccount(m.data!).decimals;
        effects.push(() => {
          rpc.accounts.set(ata!, { owner: TOKEN_PROGRAM_ID, data: new Uint8Array(165) });
          rpc.tokenBalances.set(ata!, { amount: 0n, decimals });
        });
      }
    } else if (ix.program === TOKEN_PROGRAM_ID && ix.data.length === 10 && ix.data[0] === 14) {
      const [mint, dest, authority] = ix.accounts;
      const m = rpc.accounts.get(mint!);
      if (!m) return problem('no such mint');
      const parsed = parseMintAccount(m.data!);
      if (!signers.has(authority!)) return problem('missing required signature');
      if (parsed.mintAuthority !== authority) return problem('owner does not match');
      if (ix.data[9] !== parsed.decimals) return problem('decimals mismatch');
      if (!rpc.accounts.has(dest!) && !created.has(dest!)) return problem('invalid account data');
      const amount = new DataView(ix.data.buffer, ix.data.byteOffset).getBigUint64(1, true);
      effects.push(() => {
        const b = rpc.tokenBalances.get(dest!)!;
        rpc.tokenBalances.set(dest!, { ...b, amount: b.amount + amount });
      });
    } else return problem('an instruction the faucet does not send');
  }
  return {
    problem: null,
    apply: () => {
      for (const e of effects) e();
    },
  };
}

// ── the faucet under test ────────────────────────────────────────────────────────────────────────────

const entry = (symbol: string, splMint: string, decimals: number): BridgeEntry => ({
  colour: encodeHex(nacl.randomBytes(32)),
  splMint,
  bridgeContract: encodeHex(nacl.randomBytes(32)),
  bridgeProgram: randomAddress(),
  bridgeApi: 'http://127.0.0.1:18080',
  name: `Test ${symbol}`,
  symbol,
  decimals,
});
const encodeHex = (b: Uint8Array) => Buffer.from(b).toString('hex');

function setup(
  o: {
    registryGenesis?: string;
    rpcGenesis?: string;
    file?: string | null;
    amount?: string;
    perClient?: number;
    cap?: number;
    chain?: Chain;
    keys?: { x: FaucetKey; y: FaucetKey; mx: string; my: string };
    clock?: { now: number };
    log?: ReturnType<typeof silentLog>;
    pollMs?: number;
    confirmTimeoutMs?: number;
  } = {},
) {
  const ch = o.chain ?? mockChain(o.rpcGenesis);
  const k = o.keys ?? { x: newKey(), y: newKey(), mx: randomAddress(), my: randomAddress() };
  if (!ch.rpc.accounts.has(k.mx)) {
    ch.rpc.accounts.set(k.mx, { owner: TOKEN_PROGRAM_ID, data: mintData(k.x.publicKey, 6) });
    ch.rpc.accounts.set(k.my, { owner: TOKEN_PROGRAM_ID, data: mintData(k.y.publicKey, 9) });
  }
  const registry = new BridgeRegistry('undeployed', o.registryGenesis ?? ch.rpc.genesisHash, [
    entry('X', k.mx, 6),
    entry('Y', k.my, 9),
  ]);
  const clock = o.clock ?? { now: 1_800_000_000 };
  const log = o.log ?? silentLog();
  const claims = new SplFaucetClaims({ file: o.file ?? null, periodSeconds: DAY, now: () => clock.now });
  const faucet = new SplFaucet({
    registry,
    keys: new Map([
      [k.mx, k.x],
      [k.my, k.y],
    ]),
    rpc: new FaucetSolanaRpc('http://solana-rpc.test', ch.fetch),
    claims,
    amountWhole: o.amount ?? '1000',
    periodSeconds: DAY,
    claimsPerPeriod: o.cap ?? 200,
    perClientPerPeriod: o.perClient ?? 3,
    log,
    now: () => clock.now,
    pollMs: o.pollMs ?? 1,
    confirmTimeoutMs: o.confirmTimeoutMs ?? 150,
    recheckSeconds: 0,
  });
  const client = { address: '198.51.100.7' };
  const h = harness({
    catalogue: withSplFaucet(defaultCatalogue(), {
      admit: ({ payload, client: c }) => faucet.admit(payload, c ?? 'unknown'),
      executor: faucet.executor(),
    }),
    splFaucet: (w) => faucet.info(w),
    clientAddress: () => client.address,
  });
  const claim = async (wallet: string) => {
    const res = await post(h, 'spl-faucet', { payload: { wallet } });
    const body = (await res.json()) as { job?: JobView; error?: { code: string; message: string; detail?: string } };
    if (res.status !== 202)
      return { status: res.status, error: body.error!, retryAfter: res.headers.get('retry-after') };
    await h.queue.settled(body.job!.requestId);
    const job = ((await (await h.app.request(`/v1/jobs/${body.job!.requestId}`)).json()) as { job: JobView }).job;
    return { status: 202, job };
  };
  const info = async (wallet?: string) =>
    (await (await h.app.request(`/v1/spl-faucet${wallet ? `?wallet=${wallet}` : ''}`)).json()) as SplFaucetInfo;
  return { ch, k, registry, faucet, claims, h, clock, log, client, claim, info };
}

const okResult = (r: Awaited<ReturnType<ReturnType<typeof setup>['claim']>>): SplFaucetResult => {
  if (!('job' in r) || !r.job) throw new Error(`refused: ${JSON.stringify(r)}`);
  if (r.job.state !== 'succeeded') throw new Error(`job ${r.job.state}: ${JSON.stringify(r.job.error)}`);
  return r.job.result as unknown as SplFaucetResult;
};

