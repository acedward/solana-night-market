describe('the test SPL faucet: a claim', () => {
  it('mints 1,000 X and 1,000 Y to a fresh wallet in ONE transaction paid by the faucet key, creating its accounts', async () => {
    const s = setup();
    await s.faucet.check();
    expect(s.faucet.current.kind).toBe('ready');
    const wallet = randomAddress();
    const offer = await s.info(wallet);
    expect(offer).toMatchObject({ enabled: true, periodHours: 24 });
    expect(offer.claim).toBeUndefined();
    expect(offer.tokens.map((t) => [t.symbol, t.amount])).toEqual([
      ['X', '1000000000'],
      ['Y', '1000000000000'],
    ]);
    const r = okResult(await s.claim(wallet));
    expect(s.ch.rpc.sent).toHaveLength(1);
    expect(r.signature).toBe(s.ch.rpc.sent[0]!.signature);
    // The fee payer (first signer) is X's authority; both authorities sign; the wallet does not.
    const d = decodeMessage(s.ch.rpc.sent[0]!.message);
    expect(d.keys.slice(0, d.signers).sort()).toEqual([s.k.x.publicKey, s.k.y.publicKey].sort());
    expect(d.keys[0]).toBe(s.k.x.publicKey);
    expect(d.keys.slice(0, d.signers)).not.toContain(wallet);
    expect(r.minted.map((m) => [m.symbol, m.amount, m.createdAccount])).toEqual([
      ['X', '1000000000', true],
      ['Y', '1000000000000', true],
    ]);
    expect(s.ch.balance(wallet, s.k.mx)).toBe(1_000_000_000n);
    expect(s.ch.balance(wallet, s.k.my)).toBe(1_000_000_000_000n);
    expect(r.nextClaimAt - r.at).toBe(DAY);
    expect((await s.info(wallet)).claim).toMatchObject({
      state: 'claimed',
      nextClaimAt: r.at + DAY,
      signature: r.signature,
    });
  });

  it('keeps an existing token account (CreateIdempotent) and reports it was not created', async () => {
    const s = setup();
    await s.faucet.check();
    const wallet = randomAddress();
    const ata = associatedTokenAddress(wallet, s.k.mx);
    s.ch.rpc.accounts.set(ata, { owner: TOKEN_PROGRAM_ID, data: new Uint8Array(165) });
    s.ch.rpc.tokenBalances.set(ata, { amount: 5n, decimals: 6 });
    const r = okResult(await s.claim(wallet));
    expect(r.minted.map((m) => m.createdAccount)).toEqual([false, true]);
    expect(s.ch.balance(wallet, s.k.mx)).toBe(1_000_000_005n);
  });

  it("applies SPL_FAUCET_AMOUNT in each mint's own decimals (MintToChecked carries them)", async () => {
    const s = setup({ amount: '2.5' });
    await s.faucet.check();
    const wallet = randomAddress();
    okResult(await s.claim(wallet));
    const d = decodeMessage(s.ch.rpc.sent[0]!.message);
    const mints = d.ixs.filter((i) => i.program === TOKEN_PROGRAM_ID);
    const amountOf = (data: Uint8Array) => new DataView(data.buffer, data.byteOffset).getBigUint64(1, true);
    expect(mints.map((i) => [i.accounts[0], amountOf(i.data), i.data[9]])).toEqual([
      [s.k.mx, 2_500_000n, 6],
      [s.k.my, 2_500_000_000n, 9],
    ]);
    expect(s.ch.balance(wallet, s.k.mx)).toBe(2_500_000n);
    // An amount finer than a mint's decimals, or past a u64, cannot be configured.
    const reg = new BridgeRegistry('undeployed', s.ch.rpc.genesisHash, [entry('Z', s.k.mx, 0)]);
    expect(() => faucetTokens(reg, new Map([[s.k.mx, s.k.x]]), '0.5')).toThrow(FaucetConfigError);
    expect(() => faucetTokens(reg, new Map([[s.k.mx, s.k.x]]), '18446744073709551616')).toThrow(/u64/);
  });

  it('refuses a wallet that is not a Solana address', async () => {
    const s = setup();
    await s.faucet.check();
    expect((await post(s.h, 'spl-faucet', { payload: { wallet: 'not a key' } })).status).toBe(400);
    const r = await s.claim('z'.repeat(44)); // base58, but not 32 bytes
    expect(r).toMatchObject({ status: 400, error: { code: 'spl-faucet-bad-wallet' } });
    expect(s.ch.rpc.sent).toHaveLength(0);
  });
});

